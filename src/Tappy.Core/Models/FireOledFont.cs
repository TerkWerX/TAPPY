namespace Tappy.Core.Models;

/// <summary>
/// A small, original 5x7 monospace bitmap font for the Akai Fire's 128x64
/// monochrome OLED (see FireOledTextRenderer and docs/AKAI_FIRE.md). Each
/// glyph is authored as 7 rows of 5 characters ('#' = lit, '.' = dark) so it
/// is directly readable in source, rather than as opaque byte/hex data.
/// Covers uppercase, lowercase, digits, space, and the punctuation actually
/// needed for device/layer names (". : - / ( ) '"). A character outside this
/// set has no entry and callers fall back to a blank glyph — content strings
/// are free text (layer names are user-editable), so unsupported input must
/// degrade gracefully, not throw.
/// </summary>
public static class FireOledFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;

    public static bool[,] GetGlyph(char character)
    {
        var rows = Glyphs.TryGetValue(character, out var pattern) ? pattern : Blank;
        var glyph = new bool[GlyphWidth, GlyphHeight];
        for (var y = 0; y < GlyphHeight; y++)
        {
            for (var x = 0; x < GlyphWidth; x++)
            {
                glyph[x, y] = rows[y][x] == '#';
            }
        }

        return glyph;
    }

